def print_swing_result(record: dict) -> None:
    video_id = record.get("video_id", "UNKNOWN")

    print()
    print(video_id)
    print_separator()

    print(
        f"  Validity                : "
        f"{record.get('validity_status', 'N/A')}"
    )

    print(
        f"  Baseline eligible       : "
        f"{record.get('target_baseline_eligible', 'N/A')}"
    )

    print(
        f"  Baseline mode           : "
        f"{record.get('baseline_mode', 'N/A')}"
    )

    print(
        f"  Baseline profiles       : "
        f"{record.get('baseline_profiles', 'N/A')}"
    )

    print(
        f"  Metric coverage         : "
        f"{format_float(record.get('metric_coverage_percent'), 1)}%"
    )

    print(
        f"  Comparison level        : "
        f"{record.get('comparison_level', 'N/A')}"
    )

    print(
        f"  Outside typical range   : "
        f"{record.get('outside_typical_range', 'N/A')}"
    )

    print(
        f"  Measurement confidence  : "
        f"{record.get('measurement_confidence', 'N/A')}"
    )

    largest_metric = record.get(
        "largest_difference_1_metric",
        "N/A",
    )

    largest_z = record.get(
        "largest_difference_1_robust_z",
        None,
    )

    print(
        f"  Largest difference      : "
        f"{largest_metric}"
    )

    print(
        f"  Largest robust Z        : "
        f"{format_float(largest_z, 2)}"
    )


# =============================================================================
# MAIN
# =============================================================================

def main():
    parser = argparse.ArgumentParser(
        description=(
            "Run BaseVisionAI Swing Insights V1 in batch mode "
            "for every Swing Feedback V1.2 result in a session."
        )
    )

    parser.add_argument(
        "--feedback-dir",
        required=True,
        help=(
            "Directory containing "
            "*_swing_feedback_v1_2.csv files."
        ),
    )

    parser.add_argument(
        "--output-dir",
        required=True,
        help="Directory where Swing Insights V1 outputs will be stored.",
    )

    parser.add_argument(
        "--insights-script",
        default=None,
        help=(
            "Optional explicit path to swing_insights_v1.py. "
            "If omitted, the script is expected in the same directory "
            "as this batch script."
        ),
    )

    args = parser.parse_args()

    feedback_dir = Path(args.feedback_dir)
    output_dir = Path(args.output_dir)

    if args.insights_script:
        insights_script = Path(args.insights_script)
    else:
        insights_script = (
            Path(__file__).resolve().parent
            / "swing_insights_v1.py"
        )

    print()
    print_separator("=", 92)
    print("BASEVISIONAI - BATCH SWING INSIGHTS V1")
    print_separator("=", 92)

    # -------------------------------------------------------------------------
    # Validate paths
    # -------------------------------------------------------------------------

    if not feedback_dir.exists():
        print()
        print("ERROR")
        print_separator()
        print(f"Feedback directory not found: {feedback_dir}")
        sys.exit(1)

    if not insights_script.exists():
        print()
        print("ERROR")
        print_separator()
        print(f"Swing Insights script not found: {insights_script}")
        sys.exit(1)

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # -------------------------------------------------------------------------
    # Discover swings
    # -------------------------------------------------------------------------

    feedback_files = discover_feedback_files(feedback_dir)

    if not feedback_files:
        print()
        print("ERROR")
        print_separator()
        print(
            "No Swing Feedback V1.2 files were found in:"
        )
        print(feedback_dir)
        sys.exit(1)

    print()
    print("INPUT")
    print_separator()

    print(
        f"Feedback directory        : {feedback_dir}"
    )

    print(
        f"Insights script           : {insights_script}"
    )

    print(
        f"Output directory          : {output_dir}"
    )

    print(
        f"Swings discovered         : {len(feedback_files)}"
    )

    # -------------------------------------------------------------------------
    # Run batch
    # -------------------------------------------------------------------------

    successful_records = []
    failed_records = []

    print()
    print("PROCESSING")
    print_separator()

    for index, feedback_file in enumerate(
        feedback_files,
        start=1,
    ):
        video_id = video_id_from_feedback_path(
            feedback_file
        )

        summary_file = (
            feedback_dir
            / f"{video_id}{FEEDBACK_SUMMARY_SUFFIX}"
        )

        print()
        print(
            f"[{index}/{len(feedback_files)}] "
            f"{video_id}"
        )

        if not summary_file.exists():
            message = (
                "Swing Feedback summary not found: "
                f"{summary_file}"
            )

            print(f"  FAILED: {message}")

            failed_records.append(
                {
                    "video_id": video_id,
                    "feedback_file": str(feedback_file),
                    "summary_file": str(summary_file),
                    "error": message,
                }
            )

            continue

        success, message = run_single_insights(
            insights_script=insights_script,
            feedback_file=feedback_file,
            summary_file=summary_file,
            output_dir=output_dir,
        )

        if not success:
            print("  FAILED")
            print(f"  {message}")

            failed_records.append(
                {
                    "video_id": video_id,
                    "feedback_file": str(feedback_file),
                    "summary_file": str(summary_file),
                    "error": message,
                }
            )

            continue

        try:
            record = load_insights_summary(
                output_dir=output_dir,
                video_id=video_id,
            )

            successful_records.append(record)

            print("  COMPLETE")

        except Exception as exc:
            message = (
                "Insights script completed but generated "
                f"summary could not be loaded: {exc}"
            )

            print(f"  FAILED: {message}")

            failed_records.append(
                {
                    "video_id": video_id,
                    "feedback_file": str(feedback_file),
                    "summary_file": str(summary_file),
                    "error": message,
                }
            )

    # -------------------------------------------------------------------------
    # Save combined summary
    # -------------------------------------------------------------------------

    batch_summary_path = (
        output_dir
        / "batch_swing_insights_v1_summary.csv"
    )

    failures_path = (
        output_dir
        / "batch_swing_insights_v1_failures.csv"
    )

    if successful_records:
        batch_df = build_batch_summary(
            successful_records,
            feedback_dir=feedback_dir,
            output_dir=output_dir,
        )

        batch_df.to_csv(
            batch_summary_path,
            index=False,
        )

    if failed_records:
        failed_df = pd.DataFrame(
            failed_records
        )

        failed_df.to_csv(
            failures_path,
            index=False,
        )

    # -------------------------------------------------------------------------
    # Detailed console results
    # -------------------------------------------------------------------------

    if successful_records:
        print()
        print_separator("=", 92)
        print("SWING INSIGHTS SUMMARY")
        print_separator("=", 92)

        for record in successful_records:
            print_swing_result(record)

    # -------------------------------------------------------------------------
    # Final summary
    # -------------------------------------------------------------------------

    print()
    print_separator("=", 92)
    print("BASEVISIONAI - BATCH SWING INSIGHTS V1 COMPLETE")
    print_separator("=", 92)

    print()
    print("BATCH RESULTS")
    print_separator()

    print(
        f"Swings discovered         : "
        f"{len(feedback_files)}"
    )

    print(
        f"Successful                : "
        f"{len(successful_records)}"
    )

    print(
        f"Failed                    : "
        f"{len(failed_records)}"
    )

    # -------------------------------------------------------------------------
    # Session overview
    # -------------------------------------------------------------------------

    if successful_records:
        batch_df = pd.DataFrame(
            successful_records
        )

        print()
        print("SESSION INSIGHTS")
        print_separator()

        if "comparison_level" in batch_df.columns:
            levels = (
                batch_df["comparison_level"]
                .fillna("UNKNOWN")
                .astype(str)
                .value_counts()
            )

            for level, count in levels.items():
                print(
                    f"{level:<26}: {count}"
                )

        if "metric_coverage_percent" in batch_df.columns:
            coverage = pd.to_numeric(
                batch_df["metric_coverage_percent"],
                errors="coerce",
            )

            if coverage.notna().any():
                print(
                    f"{'Mean metric coverage':<26}: "
                    f"{coverage.mean():.1f}%"
                )

        if "outside_typical_range" in batch_df.columns:
            outside = pd.to_numeric(
                batch_df["outside_typical_range"],
                errors="coerce",
            )

            if outside.notna().any():
                print(
                    f"{'Mean outside range':<26}: "
                    f"{outside.mean():.1f} metrics"
                )

        if "mean_abs_robust_z" in batch_df.columns:
            robust_z = pd.to_numeric(
                batch_df["mean_abs_robust_z"],
                errors="coerce",
            )

            if robust_z.notna().any():
                print(
                    f"{'Mean abs robust Z':<26}: "
                    f"{robust_z.mean():.2f}"
                )

    # -------------------------------------------------------------------------
    # Output files
    # -------------------------------------------------------------------------

    print()
    print("OUTPUT FILES")
    print_separator()

    if successful_records:
        print(
            f"Batch summary             : "
            f"{batch_summary_path}"
        )

    if failed_records:
        print(
            f"Failures                  : "
            f"{failures_path}"
        )

    print(
        f"Individual insights       : "
        f"{output_dir}"
    )

    # -------------------------------------------------------------------------
    # Important
    # -------------------------------------------------------------------------

    print()
    print("IMPORTANT")
    print_separator()

    print(
        "Insights describe statistical differences relative "
        "to the player's observed session baseline."
    )

    print(
        "Largest differences are ranked by absolute robust "
        "Z-score, not by baseball quality."
    )

    print(
        "Baseline-ineligible swings may still be analyzed "
        "against the eligible session baseline."
    )

    print(
        "LOW_CONFIDENCE_SWING and TEMPORAL_LOW_CONFIDENCE "
        "profiles do not contribute to the baseline."
    )

    print(
        "No GOOD/BAD swing label, biomechanical performance "
        "score, or coaching recommendation is generated."
    )

    print(
        "Projected rotation and motion metrics remain "
        "comparative 2D measurements."
    )

    print(
        "No calibrated 3D biomechanics are inferred."
    )

    print_separator("=", 92)

    # -------------------------------------------------------------------------
    # Exit status
    # -------------------------------------------------------------------------

    if failed_records:
        sys.exit(1)


if __name__ == "__main__":
    main()