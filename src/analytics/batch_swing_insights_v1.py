"""
BaseVisionAI
Batch Swing Insights V1

Runs Swing Insights V1 for every Swing Feedback V1.2 result found
inside a player/session feedback directory.

Example
-------
python src/analytics/batch_swing_insights_v1.py ^
    --feedback-dir results/swing_feedback_v1_2/player_001/session_001 ^
    --output-dir results/swing_insights_v1/player_001/session_001

PowerShell
----------
python src\analytics\batch_swing_insights_v1.py `
    --feedback-dir results\swing_feedback_v1_2\player_001\session_001 `
    --output-dir results\swing_insights_v1\player_001\session_001
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import pandas as pd


# =============================================================================
# CONSTANTS
# =============================================================================

BATCH_VERSION = "Batch Swing Insights V1"

FEEDBACK_SUFFIX = "_swing_feedback_v1_2.csv"
FEEDBACK_SUMMARY_SUFFIX = "_swing_feedback_v1_2_summary.csv"

INSIGHTS_SUFFIX = "_swing_insights_v1.csv"
INSIGHTS_SUMMARY_SUFFIX = "_swing_insights_v1_summary.csv"


# =============================================================================
# HELPERS
# =============================================================================

def print_separator(char: str = "-", width: int = 92) -> None:
    print(char * width)


def safe_read_csv(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"File not found: {path}")

    df = pd.read_csv(path)

    if df.empty:
        raise ValueError(f"CSV is empty: {path}")

    return df


def safe_value(row: pd.Series, column: str, default=None):
    if column not in row.index:
        return default

    value = row[column]

    if pd.isna(value):
        return default

    return value


def to_float(value, default=None):
    try:
        if value is None:
            return default
        return float(value)
    except (TypeError, ValueError):
        return default


def to_int(value, default=None):
    try:
        if value is None:
            return default
        return int(float(value))
    except (TypeError, ValueError):
        return default


def format_float(value, decimals: int = 2, default: str = "N/A") -> str:
    number = to_float(value)

    if number is None:
        return default

    return f"{number:.{decimals}f}"


# =============================================================================
# DISCOVERY
# =============================================================================

def discover_feedback_files(feedback_dir: Path) -> list[Path]:
    """
    Find detailed Swing Feedback V1.2 CSV files.

    Summary CSVs are excluded automatically.
    """

    files = []

    for path in sorted(feedback_dir.glob(f"*{FEEDBACK_SUFFIX}")):
        if path.name.endswith(FEEDBACK_SUMMARY_SUFFIX):
            continue

        files.append(path)

    return files


def video_id_from_feedback_path(path: Path) -> str:
    name = path.name

    if not name.endswith(FEEDBACK_SUFFIX):
        raise ValueError(
            f"Unexpected feedback filename: {path.name}"
        )

    return name[:-len(FEEDBACK_SUFFIX)]


# =============================================================================
# RUN SINGLE INSIGHTS ANALYSIS
# =============================================================================

def run_single_insights(
    insights_script: Path,
    feedback_file: Path,
    summary_file: Path,
    output_dir: Path,
) -> tuple[bool, str]:
    """
    Run swing_insights_v1.py for one swing.

    Returns
    -------
    success : bool
    message : str
    """

    command = [
        sys.executable,
        str(insights_script),
        "--feedback",
        str(feedback_file),
        "--summary",
        str(summary_file),
        "--output-dir",
        str(output_dir),
    ]

    result = subprocess.run(
        command,
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        error_message = result.stderr.strip()

        if not error_message:
            error_message = result.stdout.strip()

        if not error_message:
            error_message = (
                f"Swing Insights returned exit code {result.returncode}"
            )

        return False, error_message

    return True, result.stdout.strip()


# =============================================================================
# LOAD GENERATED INSIGHTS SUMMARY
# =============================================================================

def load_insights_summary(
    output_dir: Path,
    video_id: str,
) -> dict:
    """
    Read the summary generated by swing_insights_v1.py.
    """

    path = output_dir / f"{video_id}{INSIGHTS_SUMMARY_SUFFIX}"

    df = safe_read_csv(path)
    row = df.iloc[0]

    record = {
        "video_id": video_id,
        "insights_summary_file": str(path),
    }

    for column in df.columns:
        record[column] = row[column]

    return record


