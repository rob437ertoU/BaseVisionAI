from pathlib import Path
import argparse
import csv

import cv2
from ultralytics import YOLO


# ============================================================
# PROJECT PATHS
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parents[2]

DEFAULT_POSE_MODEL = "yolo11n-pose.pt"

DEFAULT_OUTPUT_DIR = (
    PROJECT_ROOT
    / "results"
    / "batter_pose_v2"
)


# ============================================================
# CONFIG
# ============================================================

DEFAULT_CONF = 0.25
DEFAULT_IMGSZ = 640

# Expand batter bounding box to avoid cutting arms/bat
ROI_MARGIN_X = 0.20
ROI_MARGIN_Y = 0.15


# ============================================================
# COCO 17 KEYPOINT NAMES
# ============================================================

KEYPOINT_NAMES = [
    "nose",
    "left_eye",
    "right_eye",
    "left_ear",
    "right_ear",
    "left_shoulder",
    "right_shoulder",
    "left_elbow",
    "right_elbow",
    "left_wrist",
    "right_wrist",
    "left_hip",
    "right_hip",
    "left_knee",
    "right_knee",
    "left_ankle",
    "right_ankle",
]


# ============================================================
# ARGUMENTS
# ============================================================

def parse_args():

    parser = argparse.ArgumentParser(
        description="BaseVisionAI - Batter Pose V2"
    )

    parser.add_argument(
        "--video",
        type=str,
        required=True,
        help="Original input video"
    )

    parser.add_argument(
        "--tracking-csv",
        type=str,
        required=True,
        help="CSV generated by track_batter_v2.py"
    )

    parser.add_argument(
        "--model",
        type=str,
        default=DEFAULT_POSE_MODEL,
        help="YOLO pose model"
    )

    parser.add_argument(
        "--output-dir",
        type=str,
        default=str(DEFAULT_OUTPUT_DIR),
        help="Output directory"
    )

    parser.add_argument(
        "--conf",
        type=float,
        default=DEFAULT_CONF,
        help="Pose confidence threshold"
    )

    parser.add_argument(
        "--imgsz",
        type=int,
        default=DEFAULT_IMGSZ,
        help="Pose inference image size"
    )

    parser.add_argument(
        "--device",
        type=str,
        default="0",
        help="CUDA device"
    )

    return parser.parse_args()


# ============================================================
# LOAD TRACKING CSV
# ============================================================

def load_tracking_csv(csv_path):

    tracking = {}

    with open(
        csv_path,
        "r",
        encoding="utf-8"
    ) as f:

        reader = csv.DictReader(f)

        for row in reader:

            frame = int(row["frame"])

            state = row["state"]

            # ------------------------------------------------
            # Frames with no usable bounding box
            # ------------------------------------------------

            if (
                row["x1"] == ""
                or row["y1"] == ""
                or row["x2"] == ""
                or row["y2"] == ""
            ):

                tracking[frame] = {
                    "state": state,
                    "bbox": None
                }

                continue

            tracking[frame] = {
                "state": state,
                "bbox": [
                    float(row["x1"]),
                    float(row["y1"]),
                    float(row["x2"]),
                    float(row["y2"])
                ]
            }

    return tracking


# ============================================================
# EXPAND ROI
# ============================================================

def expand_bbox(
    bbox,
    frame_width,
    frame_height,
):

    x1, y1, x2, y2 = bbox

    width = x2 - x1
    height = y2 - y1

    margin_x = width * ROI_MARGIN_X
    margin_y = height * ROI_MARGIN_Y

    x1_new = max(
        0,
        int(x1 - margin_x)
    )

    y1_new = max(
        0,
        int(y1 - margin_y)
    )

    x2_new = min(
        frame_width - 1,
        int(x2 + margin_x)
    )

    y2_new = min(
        frame_height - 1,
        int(y2 + margin_y)
    )

    return (
        x1_new,
        y1_new,
        x2_new,
        y2_new
    )


# ============================================================
# SELECT BEST POSE
# ============================================================

def select_best_pose(result):

    if result.boxes is None:
        return None

    if len(result.boxes) == 0:
        return None

    best_index = None
    best_conf = -1.0

    for i, box in enumerate(result.boxes):

        confidence = float(
            box.conf[0].item()
        )

        if confidence > best_conf:

            best_conf = confidence
            best_index = i

    return best_index


# ============================================================
# MAIN
# ============================================================

def main():

    args = parse_args()

    # --------------------------------------------------------
    # Paths
    # --------------------------------------------------------

    video_path = Path(args.video).resolve()
    tracking_csv_path = Path(
        args.tracking_csv
    ).resolve()

    output_dir = Path(
        args.output_dir
    ).resolve()

    if not video_path.exists():

        raise FileNotFoundError(
            f"Video not found:\n{video_path}"
        )

    if not tracking_csv_path.exists():

        raise FileNotFoundError(
            f"Tracking CSV not found:\n"
            f"{tracking_csv_path}"
        )

    output_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    video_name = video_path.stem

    output_video = (
        output_dir
        / f"{video_name}_batter_pose_v2.mp4"
    )

    output_csv = (
        output_dir
        / f"{video_name}_batter_pose_v2.csv"
    )

    # --------------------------------------------------------
    # Load tracking data
    # --------------------------------------------------------

    tracking_data = load_tracking_csv(
        tracking_csv_path
    )

    # --------------------------------------------------------
    # Load pose model
    # --------------------------------------------------------

    print()
    print("=" * 70)
    print("BaseVisionAI - Batter Pose V2")
    print("=" * 70)

    print(f"Video        : {video_path}")
    print(f"Tracking CSV : {tracking_csv_path}")
    print(f"Pose model   : {args.model}")
    print(f"Confidence   : {args.conf}")
    print(f"Image size   : {args.imgsz}")
    print(f"Device       : {args.device}")

    print("=" * 70)
    print()

    model = YOLO(
        args.model
    )

    # --------------------------------------------------------
    # Open video
    # --------------------------------------------------------

    cap = cv2.VideoCapture(
        str(video_path)
    )

    if not cap.isOpened():

        raise RuntimeError(
            f"Could not open video:\n"
            f"{video_path}"
        )

    fps = cap.get(
        cv2.CAP_PROP_FPS
    )

    width = int(
        cap.get(
            cv2.CAP_PROP_FRAME_WIDTH
        )
    )

    height = int(
        cap.get(
            cv2.CAP_PROP_FRAME_HEIGHT
        )
    )

    total_frames = int(
        cap.get(
            cv2.CAP_PROP_FRAME_COUNT
        )
    )

    fourcc = cv2.VideoWriter_fourcc(
        *"mp4v"
    )

    writer = cv2.VideoWriter(
        str(output_video),
        fourcc,
        fps,
        (width, height)
    )

    # --------------------------------------------------------
    # CSV storage
    # --------------------------------------------------------

    csv_rows = []

    frame_number = 0

    pose_detected_count = 0
    pose_missing_count = 0

    # ========================================================
    # FRAME LOOP
    # ========================================================

    while True:

        ret, frame = cap.read()

        if not ret:
            break

        frame_number += 1

        # ----------------------------------------------------
        # Tracking info
        # ----------------------------------------------------

        tracking_info = tracking_data.get(
            frame_number
        )

        if tracking_info is None:

            tracking_state = "NO_TRACK_DATA"
            batter_bbox = None

        else:

            tracking_state = (
                tracking_info["state"]
            )

            batter_bbox = (
                tracking_info["bbox"]
            )

        # ----------------------------------------------------
        # Base CSV row
        # ----------------------------------------------------

        row = {
            "frame": frame_number,
            "time_sec":
                (frame_number - 1) / fps,
            "tracking_state":
                tracking_state,
            "pose_detected": 0,
            "pose_box_confidence": "",
        }

        # ----------------------------------------------------
        # Initialize keypoints empty
        # ----------------------------------------------------

        for name in KEYPOINT_NAMES:

            row[f"{name}_x"] = ""
            row[f"{name}_y"] = ""
            row[f"{name}_conf"] = ""

        # ----------------------------------------------------
        # No batter bbox
        # ----------------------------------------------------

        if batter_bbox is None:

            pose_missing_count += 1

            cv2.putText(
                frame,
                "BATTER POSE: NO ROI",
                (30, 40),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.8,
                (0, 0, 255),
                2,
                cv2.LINE_AA
            )

            writer.write(frame)
            csv_rows.append(row)

            continue

        # ----------------------------------------------------
        # Expand batter ROI
        # ----------------------------------------------------

        rx1, ry1, rx2, ry2 = expand_bbox(
            batter_bbox,
            width,
            height
        )

        # ----------------------------------------------------
        # Validate ROI
        # ----------------------------------------------------

        if (
            rx2 <= rx1
            or ry2 <= ry1
        ):

            pose_missing_count += 1

            writer.write(frame)
            csv_rows.append(row)

            continue

        roi = frame[
            ry1:ry2,
            rx1:rx2
        ]

        # ----------------------------------------------------
        # Pose inference
        # ----------------------------------------------------

        results = model.predict(
            source=roi,
            conf=args.conf,
            imgsz=args.imgsz,
            device=args.device,
            verbose=False
        )

        result = results[0]

        best_index = select_best_pose(
            result
        )

        # ----------------------------------------------------
        # No pose found
        # ----------------------------------------------------

        if best_index is None:

            pose_missing_count += 1

            cv2.rectangle(
                frame,
                (rx1, ry1),
                (rx2, ry2),
                (0, 255, 255),
                2
            )

            cv2.putText(
                frame,
                "BATTER POSE: MISSING",
                (
                    rx1,
                    max(30, ry1 - 10)
                ),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.7,
                (0, 255, 255),
                2,
                cv2.LINE_AA
            )

            writer.write(frame)
            csv_rows.append(row)

            continue

        # ----------------------------------------------------
        # Pose found
        # ----------------------------------------------------

        pose_detected_count += 1

        row["pose_detected"] = 1

        pose_box_conf = float(
            result.boxes[
                best_index
            ].conf[0].item()
        )

        row["pose_box_confidence"] = (
            pose_box_conf
        )

        # ----------------------------------------------------
        # Get keypoints
        # ----------------------------------------------------

        keypoints = (
            result.keypoints[
                best_index
            ]
        )

        xy = (
            keypoints.xy[0]
            .cpu()
            .numpy()
        )

        if keypoints.conf is not None:

            kp_conf = (
                keypoints.conf[0]
                .cpu()
                .numpy()
            )

        else:

            kp_conf = [
                1.0
                for _ in range(
                    len(xy)
                )
            ]

        # ----------------------------------------------------
        # Convert ROI coordinates back to full frame
        # ----------------------------------------------------

        full_keypoints = []

        for i, name in enumerate(
            KEYPOINT_NAMES
        ):

            if i >= len(xy):
                break

            kp_x = float(
                xy[i][0]
            )

            kp_y = float(
                xy[i][1]
            )

            confidence = float(
                kp_conf[i]
            )

            full_x = kp_x + rx1
            full_y = kp_y + ry1

            row[f"{name}_x"] = (
                full_x
            )

            row[f"{name}_y"] = (
                full_y
            )

            row[f"{name}_conf"] = (
                confidence
            )

            full_keypoints.append(
                (
                    int(full_x),
                    int(full_y),
                    confidence
                )
            )

        # ----------------------------------------------------
        # Draw batter ROI
        # ----------------------------------------------------

        cv2.rectangle(
            frame,
            (rx1, ry1),
            (rx2, ry2),
            (255, 255, 0),
            2
        )

        # ----------------------------------------------------
        # Draw keypoints
        # ----------------------------------------------------

        for (
            kp_x,
            kp_y,
            confidence
        ) in full_keypoints:

            if confidence < 0.30:
                continue

            cv2.circle(
                frame,
                (kp_x, kp_y),
                4,
                (0, 255, 0),
                -1
            )

        # ----------------------------------------------------
        # Draw skeleton
        # ----------------------------------------------------

        skeleton_connections = [
            (5, 6),

            (5, 7),
            (7, 9),

            (6, 8),
            (8, 10),

            (5, 11),
            (6, 12),

            (11, 12),

            (11, 13),
            (13, 15),

            (12, 14),
            (14, 16),
        ]

        for a, b in skeleton_connections:

            if (
                a >= len(full_keypoints)
                or b >= len(full_keypoints)
            ):
                continue

            ax, ay, ac = (
                full_keypoints[a]
            )

            bx, by, bc = (
                full_keypoints[b]
            )

            if (
                ac < 0.30
                or bc < 0.30
            ):
                continue

            cv2.line(
                frame,
                (ax, ay),
                (bx, by),
                (0, 255, 0),
                2
            )

        # ----------------------------------------------------
        # HUD
        # ----------------------------------------------------

        label = (
            f"BATTER POSE "
            f"{pose_box_conf:.2f}"
        )

        cv2.putText(
            frame,
            label,
            (
                rx1,
                max(30, ry1 - 10)
            ),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.7,
            (0, 255, 0),
            2,
            cv2.LINE_AA
        )

        writer.write(frame)

        csv_rows.append(row)

        # ----------------------------------------------------
        # Progress
        # ----------------------------------------------------

        if frame_number % 30 == 0:

            print(
                f"\rProcessing "
                f"{frame_number}/{total_frames}",
                end="",
                flush=True
            )

    # ========================================================
    # CLEANUP
    # ========================================================

    cap.release()
    writer.release()

    # --------------------------------------------------------
    # Save CSV
    # --------------------------------------------------------

    if csv_rows:

        with open(
            output_csv,
            "w",
            newline="",
            encoding="utf-8"
        ) as f:

            writer_csv = (
                csv.DictWriter(
                    f,
                    fieldnames=
                        csv_rows[0].keys()
                )
            )

            writer_csv.writeheader()
            writer_csv.writerows(
                csv_rows
            )

    # --------------------------------------------------------
    # Summary
    # --------------------------------------------------------

    print()
    print()

    print("=" * 70)
    print("BATTER POSE V2 SUMMARY")
    print("=" * 70)

    print(
        f"Frames total        : "
        f"{frame_number}"
    )

    print(
        f"Pose detected       : "
        f"{pose_detected_count}"
    )

    print(
        f"Pose missing        : "
        f"{pose_missing_count}"
    )

    if frame_number > 0:

        coverage = (
            pose_detected_count
            / frame_number
            * 100.0
        )

    else:

        coverage = 0.0

    print(
        f"Pose coverage       : "
        f"{coverage:.2f}%"
    )

    print()

    print(
        f"Video saved         : "
        f"{output_video}"
    )

    print(
        f"CSV saved           : "
        f"{output_csv}"
    )

    print("=" * 70)


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()